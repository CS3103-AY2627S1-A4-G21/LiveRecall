# Configuration for server-side recovery history.
# The specification requires retaining at least 60 seconds of finalized captions
# for client recovery. We retain up to 75 seconds to provide a safe buffer for
# network jitter and connection handshakes.
DEFAULT_HISTORY_WINDOW_SECONDS: float = 75.0


@dataclass
class SegmentState:
    """Represents the latest accepted state of a caption segment."""
    session: str
    segment: int
    revision: int
    source_ts: float
    final: bool
    text: str
    raw_msg: dict[str, Any]
    raw_json: str | None = None
    arrival_ts: float = field(default_factory=time.time)


class SessionState:
    """Manages caption revisions, finalized history, and bounded state for a session.

    Time basis for history expiry:
        Expiry is evaluated by comparing the caption's original `source_ts` against
        `now - max_history_seconds`, where `now` defaults to server wall-clock time
        `time.time()`. Because `source_ts` is generated by the caption source using
        Unix epoch seconds, this aligns with elapsed real time.
    Expiry behavior when the source is idle:
        When the caption source stops producing captions, server wall-clock time `now`
        continues advancing via `periodic_prune_task()`. Finalized captions older than
        `max_history_seconds` are pruned from `finalized_history` and from the
        segment revision index `segments`. The latest active provisional segment
        (if any) is preserved so that in-flight transcription context is never lost.
        When pruned segments expire, `oldest_retained_segment` advances so that any
        subsequent late/stale updates for those segments are rejected.
    """

    def __init__(self, session_id: str, max_history_seconds: float = DEFAULT_HISTORY_WINDOW_SECONDS) -> None:
        self.session_id: str = session_id
        self.max_history_seconds: float = max_history_seconds
        # Mapping from segment number to latest accepted SegmentState
        self.segments: dict[int, SegmentState] = {}
        # Chronologically ordered sequence of finalized SegmentState
        self.finalized_history: deque[SegmentState] = deque()
        # Pointer to the current provisional active segment, if any
        self.latest_active_segment: int | None = None
        # Highest segment number among segments that have been finalized and pruned
        self.oldest_retained_segment: int = 0
        self.last_activity_ts: float = time.time()

    def accept_caption(
        self,
        msg: dict[str, Any],
        now: float | None = None,
        raw_json: str | None = None,
    ) -> bool:
        """Validate and track caption updates.

        Returns True if the update is accepted and stored; False if rejected
        (e.g., stale, duplicate, or provisional update attempting to overwrite final).
        """
        if now is None:
            now = time.time()
        self.last_activity_ts = now

        # Validate message type if present
        if msg.get("type") not in ("CAPTION_UPDATE", None):
            return False

        # Extract required fields; reject malformed messages safely
        try:
            segment = int(msg["segment"])
            revision = int(msg["revision"])
            source_ts = float(msg["source_ts"])
            is_final = bool(msg.get("final", False))
            text = str(msg.get("text", ""))
        except (KeyError, ValueError, TypeError):
            return False

        if segment < 1 or revision < 1:
            return False

        # Reject updates for segments that have already expired and been pruned
        if segment <= self.oldest_retained_segment:
            return False

        current = self.segments.get(segment)
        if current is not None:
            # Prevent accepted finalized state from being overwritten by provisional state
            if current.final:
                if not is_final:
                    return False
                if revision <= current.revision:
                    return False
            else:
                # For active provisional segments, ignore duplicate and older revisions
                if revision <= current.revision:
                    return False

        # Store accepted state before broadcasting
        seg_state = SegmentState(
            session=self.session_id,
            segment=segment,
            revision=revision,
            source_ts=source_ts,
            final=is_final,
            text=text,
            raw_msg=dict(msg),
            raw_json=raw_json,
            arrival_ts=now,
        )
        self.segments[segment] = seg_state

        if is_final:
            if current is not None and current.final:
                for idx, entry in enumerate(self.finalized_history):
                    if entry.segment == segment:
                        self.finalized_history[idx] = seg_state
                        break
                else:
                    self.finalized_history.append(seg_state)
            else:
                self.finalized_history.append(seg_state)

            if self.latest_active_segment == segment:
                self.latest_active_segment = None
        else:
            self.latest_active_segment = segment

        # Prune expired history
        self.prune_history(now)
        return True

    def prune_history(self, now: float | None = None) -> None:
        """Prune finalized history and revision indexes older than retention window."""
        if now is None:
            now = time.time()

        cutoff = now - self.max_history_seconds

        # 1. Prune expired finalized items from history and segment index
        while self.finalized_history and self.finalized_history[0].source_ts < cutoff:
            expired = self.finalized_history.popleft()
            self.segments.pop(expired.segment, None)
            if expired.segment > self.oldest_retained_segment:
                self.oldest_retained_segment = expired.segment

        # 2. Prune abandoned provisional segments older than cutoff
        # (preserving the latest active provisional segment)
        abandoned = [
            seg for seg, st in self.segments.items()
            if seg != self.latest_active_segment and st.source_ts < cutoff
        ]
        for seg in abandoned:
            self.segments.pop(seg, None)
            if seg > self.oldest_retained_segment:
                self.oldest_retained_segment = seg

    def get_history(
        self,
        last_segment: int = 0,
        last_revision: int = 0,
        history_seconds: float = 30.0,
        now: float | None = None,
    ) -> list[dict[str, Any]]:
        """Return finalized captions eligible for recovery or late join."""
        if now is None:
            now = time.time()

        effective_window = min(60.0, max(0.0, history_seconds))

        if effective_window == 0:
            return []

        cutoff = now - effective_window

        result = []
        for item in self.finalized_history:
            if item.source_ts >= cutoff:
                if item.segment > last_segment or (
                    item.segment == last_segment and item.revision > last_revision
                ):
                    result.append(dict(item.raw_msg))
        result.sort(key=lambda item: (item["segment"], item["revision"]))
        return result


class ServerState:
    """Encapsulates all session states and global server configuration."""

    def __init__(self, max_history_seconds: float = DEFAULT_HISTORY_WINDOW_SECONDS) -> None:
        self.max_history_seconds: float = max_history_seconds
        self.sessions: dict[str, SessionState] = {}

    def reset(self) -> None:
        self.sessions.clear()

    def get_session(self, session_id: str) -> SessionState:
        if session_id not in self.sessions:
            self.sessions[session_id] = SessionState(
                session_id=session_id,
                max_history_seconds=self.max_history_seconds,
            )
        return self.sessions[session_id]

    def accept_caption(
        self,
        msg: dict[str, Any],
        now: float | None = None,
        raw_json: str | None = None,
    ) -> bool:
        session_id = str(msg.get("session") or "L1")
        return self.get_session(session_id).accept_caption(msg, now=now, raw_json=raw_json)

    def prune_history(self, now: float | None = None) -> None:
        if now is None:
            now = time.time()
        for session in list(self.sessions.values()):
            session.prune_history(now=now)

    def get_history(
        self,
        session_id: str = "L1",
        last_segment: int = 0,
        last_revision: int = 0,
        history_seconds: float = 30.0,
        now: float | None = None,
    ) -> list[dict[str, Any]]:
        session = self.sessions.get(session_id)
        if not session:
            return []
        return session.get_history(last_segment, last_revision, history_seconds, now=now)


# Global server state instance
STATE: ServerState = ServerState()


def accept_caption(
    msg: dict[str, Any],
    now: float | None = None,
    raw_json: str | None = None,
) -> bool:
    """Revision acceptance helper."""
    return STATE.accept_caption(msg, now=now, raw_json=raw_json)


def prune_history(now: float | None = None) -> None:
    """History and revision index expiry helper."""
    STATE.prune_history(now=now)


DEFAULT_QUEUE_CAPACITY: int = 64
HARD_QUEUE_LIMIT: int = 128
OVERLOAD_WATERMARK: int = 15
OVERLOAD_LAG_THRESHOLD: float = 0.250  # 250 ms head-of-line delay
OVERLOAD_SEND_THRESHOLD: float = 0.050  # 50 ms TCP send delay
HYSTERESIS_DEPTH: int = 5
HYSTERESIS_LAG: float = 0.050  # 50 ms
# Flow control: at most FLOW_WINDOW messages may be sent to a client before a pong confirms
# it has read them. A WebSocket peer answers a ping only after reading everything sent before
# it, so each pong is a cumulative acknowledgement.
FLOW_WINDOW: int = 4
# Slow-reader detection. A pong's latency is the client's network round trip plus any time the
# ping waited behind unread messages. Compared with the client's own minimum round trip, a lost
# packet adds a few round trips while a slow reader's backlog adds seconds. A pong slower than
# SLOW_RTT_FACTOR x the minimum (and above SLOW_MIN_LATENCY, half the freshness limit, below
# which captions are still fresh) puts the client in slow mode: final captions only, until
# SLOW_EXIT_MESSAGES further messages are confirmed without another slow pong.
# A link that is congested from the start (e.g. limited bandwidth) also inflates the minimum, so
# STALE_PONG_STREAK successive round trips slower than FRESHNESS_LIMIT enter slow mode as well.
FRESHNESS_LIMIT: float = 0.500
SLOW_RTT_FACTOR: float = 10.0
SLOW_MIN_LATENCY: float = FRESHNESS_LIMIT / 2
MIN_RTT_SAMPLES: int = 3
STALE_PONG_STREAK: int = 3
SLOW_EXIT_MESSAGES: int = 50


@dataclass
class PendingItem:
    segment: int
    revision: int
    final: bool
    payload: str
    enqueued_at: float = field(default_factory=time.time)


class CoalescingQueue:
    """Bounded, semantics-aware per-client queue with strain-aware backpressure.

    - Under normal conditions: Behaves as a strict FIFO, preserving 100% revision coverage.
    - Under strain (depth >= watermark OR head_age >= 250ms OR send_ema >= 50ms OR the
      client's flow window is full): Obsolete provisional revisions of the same segment
      are replaced in-place.
    - Under capacity exhaustion or slow mode: Oldest unfinalized provisional items are
      evicted to guarantee delivery of final captions, while preserving the latest available
      revision of any currently active segment in a dedicated slot without unbounded queue growth.
    - INVARIANT: Final captions are NEVER dropped or overwritten by provisional revisions.
    """

    def __init__(
        self,
        maxsize: int = DEFAULT_QUEUE_CAPACITY,
        overload_watermark: int = OVERLOAD_WATERMARK,
    ) -> None:
        self.maxsize = maxsize
        self.overload_watermark = overload_watermark
        self._items: deque[PendingItem] = deque()
        # Maps segment -> PendingItem for pending provisional updates in _items
        self._provisional_map: dict[int, PendingItem] = {}
        # Dedicated slot preserving the latest revision of the currently active segment under overload/slow mode
        self._active_provisional: PendingItem | None = None
        self._ready: asyncio.Event = asyncio.Event()
        self._unfinished_tasks: int = 0
        self.last_send_duration_ema: float = 0.0
        self._strained: bool = False
        # Set by client_sender while the client has FLOW_WINDOW unconfirmed messages
        self.flow_blocked: bool = False

    def task_done(self) -> None:
        if self._unfinished_tasks > 0:
            self._unfinished_tasks -= 1

    def qsize(self) -> int:
        return len(self._items) + (1 if self._active_provisional is not None else 0)

    def empty(self) -> bool:
        return len(self._items) == 0 and self._active_provisional is None

    def update_send_metric(self, duration: float) -> None:
        """Track transport-level backpressure via exponential moving average."""
        self.last_send_duration_ema = 0.8 * self.last_send_duration_ema + 0.2 * duration

    def is_strained(self) -> bool:
        """Determines if the client is experiencing network or consumption strain, with hysteresis."""
        depth = len(self._items)
        head_age = (time.time() - self._items[0].enqueued_at) if self._items else 0.0

        if not self._strained:
            # Overload trigger
            if (
                depth >= self.overload_watermark
                or head_age >= OVERLOAD_LAG_THRESHOLD
                or self.last_send_duration_ema >= OVERLOAD_SEND_THRESHOLD
                or self.flow_blocked
            ):
                self._strained = True
        else:
            # Hysteresis recovery trigger: reset to unconstrained only when queue drains
            if (
                depth <= HYSTERESIS_DEPTH
                and head_age <= HYSTERESIS_LAG
                and self.last_send_duration_ema < OVERLOAD_SEND_THRESHOLD
                and not self.flow_blocked
            ):
                self._strained = False

        return self._strained

    async def get(self) -> str:
        """Await next serialized payload to transmit (drop-in replacement for asyncio.Queue.get)."""
        while not self._items and self._active_provisional is None:
            self._ready.clear()
            await self._ready.wait()

        if self._items:
            item = self._items.popleft()
            self._untrack(item)
            self._unfinished_tasks += 1
            return item.payload
        else:
            item = self._active_provisional
            self._active_provisional = None
            self._untrack(item)
            self._unfinished_tasks += 1
            return item.payload

    def get_nowait(self) -> str:
        """Synchronously pop the next item or raise asyncio.QueueEmpty."""
        if self._items:
            item = self._items.popleft()
            self._untrack(item)
            self._unfinished_tasks += 1
            return item.payload
        elif self._active_provisional is not None:
            item = self._active_provisional
            self._active_provisional = None
            self._untrack(item)
            self._unfinished_tasks += 1
            return item.payload
        else:
            raise asyncio.QueueEmpty()

    def put_nowait(self, raw_message: str) -> None:
        """Generic enqueue for initial HISTORY and control messages."""
        item = PendingItem(segment=0, revision=0, final=True, payload=raw_message)
        self._items.append(item)
        self._ready.set()

    def enqueue_caption(
        self,
        segment: int,
        revision: int,
        is_final: bool,
        payload: str,
        slow_mode: bool = False,
    ) -> bool:
        """Non-blocking semantic enqueue for caption updates. Returns False if hard ceiling exceeded."""
        # 0. ACTIVE PROVISIONAL MANAGEMENT:
        # If the dedicated active provisional slot holds this segment, update or clear it.
        if self._active_provisional is not None and self._active_provisional.segment == segment:
            if is_final:
                # Segment finalized: active provisional is superseded by the final caption
                self._active_provisional = None
            else:
                # Newer provisional revision replaces the active provisional in place
                self._active_provisional.revision = revision
                self._active_provisional.payload = payload
                self._active_provisional.enqueued_at = time.time()
                return True

        # 1. IN-PLACE COALESCING: Only under strain or slow mode, replace an unsent provisional revision for this segment.
        # A healthy client keeps every revision, even when a burst queues several before its sender runs.
        if segment in self._provisional_map and (self.is_strained() or slow_mode):
            pending = self._provisional_map[segment]
            pending.revision = revision
            pending.final = is_final
            pending.payload = payload
            pending.enqueued_at = time.time()  # Refresh timestamp to newest
            if is_final:
                del self._provisional_map[segment]
            return True

        # 2. FINAL CAPTIONS: Durable state (must be preserved)
        if is_final:
            if len(self._items) >= self.maxsize:
                self._evict_oldest_provisional()
            # If client is catastrophically behind (> HARD_QUEUE_LIMIT finals), signal overflow
            if len(self._items) >= HARD_QUEUE_LIMIT:
                return False
            # Queued behind any unsent provisional of this segment, so nothing may coalesce ahead of it
            self._provisional_map.pop(segment, None)
            item = PendingItem(segment, revision, True, payload)
            self._items.append(item)
            self._ready.set()
            return True

        # 3. PROVISIONAL CAPTIONS:
        # Under slow mode: Do not fill queue with intermediate provisional revisions;
        # preserve the latest revision of the active segment in the dedicated slot.
        if slow_mode:
            self._active_provisional = PendingItem(segment, revision, False, payload)
            self._ready.set()
            return True

        # Normal operation: Queue is healthy and not strained, preserve full revision stream
        if not self.is_strained():
            item = PendingItem(segment, revision, False, payload)
            self._items.append(item)
            self._provisional_map[segment] = item
            self._ready.set()
            return True
        else:
            # Under strain: Backpressure detected
            if len(self._items) >= self.maxsize:
                # Evict an older provisional update to make room
                if not self._evict_oldest_provisional():
                    # If entire queue is full of finals, preserve latest revision of the
                    # active segment in the dedicated slot rather than dropping it.
                    self._active_provisional = PendingItem(segment, revision, False, payload)
                    self._ready.set()
                    return True
            item = PendingItem(segment, revision, False, payload)
            self._items.append(item)
            self._provisional_map[segment] = item
            self._ready.set()
            return True

    def _evict_oldest_provisional(self) -> bool:
        """Evict oldest unfinalized provisional item from queue to guarantee room for finals."""
        for item in list(self._items):
            if not item.final and item.segment > 0:
                self._items.remove(item)
                self._untrack(item)
                return True
        return False

    def _untrack(self, item: PendingItem) -> None:
        """Forget item as its segment's newest unsent provisional, if it still is.

        Without strain a segment may have several queued revisions; the map must keep
        pointing at the newest one when an older one is sent or evicted.
        """
        if self._provisional_map.get(item.segment) is item:
            del self._provisional_map[item.segment]


@dataclass(eq=False)
class ClientConnection:
    ws: Any
    session: str
    queue: CoalescingQueue = field(default_factory=CoalescingQueue)
    closing: bool = False
    close_task: asyncio.Task | None = None
    # Flow control: messages sent, and messages confirmed by a pong
    sent: int = 0
    acked: int = 0
    window_open: asyncio.Event = field(default_factory=asyncio.Event)
    # Slow-reader detection (see SLOW_RTT_FACTOR)
    min_rtt: float = math.inf
    rtt_samples: int = 0
    stale_pongs: int = 0
    # Value of `sent` when the last counted stale pong arrived
    stale_pong_mark: int = 0
    slow_mode: bool = False
    confirmed_since_slow: int = 0


CLIENTS: set[ClientConnection] = set()


def record_pong(client: ClientConnection, sent_at_ping: int, latency: float) -> None:
    """Update flow-control and slow-reader state from one answered ping."""
    newly_confirmed = max(0, sent_at_ping - client.acked)
    client.acked = max(client.acked, sent_at_ping)

    slow_pong = (
        client.rtt_samples >= MIN_RTT_SAMPLES
        and latency > SLOW_MIN_LATENCY
        and latency > SLOW_RTT_FACTOR * client.min_rtt
    )
    client.min_rtt = min(client.min_rtt, latency)
    client.rtt_samples += 1

    if latency > FRESHNESS_LIMIT:
        # Pings sent during the same stall are delayed together, so count a stale pong only
        # if its ping was sent after the previous counted one arrived
        if sent_at_ping > client.stale_pong_mark:
            client.stale_pongs += 1
            client.stale_pong_mark = client.sent
    else:
        client.stale_pongs = 0

    if slow_pong or client.stale_pongs >= STALE_PONG_STREAK:
        client.slow_mode = True
        client.confirmed_since_slow = 0
    elif client.slow_mode:
        client.confirmed_since_slow += newly_confirmed
        if client.confirmed_since_slow >= SLOW_EXIT_MESSAGES:
            client.slow_mode = False


async def send_flow_ping(client: ClientConnection) -> None:
    """Ping the client; its pong confirms every message sent before the ping."""
    sent_at_ping = client.sent
    pong_received = await client.ws.ping()

    def on_pong(fut: asyncio.Future) -> None:
        # Pending pings fail with ConnectionClosed when the socket closes
        if not fut.cancelled() and fut.exception() is None:
            record_pong(client, sent_at_ping, fut.result())
        client.window_open.set()

    pong_received.add_done_callback(on_pong)


async def client_sender(client: ClientConnection) -> None:
    """Send this connection's queued messages in order, at most FLOW_WINDOW ahead of the client."""
    try:
        while True:
            # Wait for room in the window *before* taking a message: while the client is
            # behind, new revisions stay in the queue, where they can still be coalesced.
            while client.sent - client.acked >= FLOW_WINDOW:
                # Also cancelled by handle_client; this just exits sooner
                if client.closing:
                    return
                client.queue.flow_blocked = True
                client.window_open.clear()
                await client.window_open.wait()
            client.queue.flow_blocked = False

            message = await client.queue.get()
            t0 = time.time()

            try:
                await client.ws.send(message)
                client.queue.update_send_metric(time.time() - t0)
            finally:
                client.queue.task_done()

            client.sent += 1
            # Ping after every message, so a pong always covers everything sent so far
            await send_flow_ping(client)

    except websockets.exceptions.ConnectionClosed:
        pass

    except Exception:
        # Closing the socket also wakes handle_client's receive loop,
        # allowing its cleanup block to run.
        await client.ws.close(
            code=1011,
            reason="Client sender failed",
        )


def enqueue_live_update(
    session: str,
    segment: int,
    revision: int,
    is_final: bool,
    raw_message: str,
) -> None:
    """Queue an accepted update to matching clients without blocking."""
    for client in tuple(CLIENTS):
        if client.closing or client.session != session:
            continue

        ok = client.queue.enqueue_caption(
            segment=segment,
            revision=revision,
            is_final=is_final,
            payload=raw_message,
            slow_mode=client.slow_mode,
        )

        if not ok:
            # Catastrophic lag beyond hard ceiling (>128 finals accumulated)
            client.closing = True
            CLIENTS.discard(client)
            client.close_task = asyncio.create_task(
                client.ws.close(
                    code=1013,
                    reason="Client lagged beyond recovery limits; reconnect to recover",
                )
            )


async def handle_source(ws, hello: dict[str, Any]) -> None:
    session = hello.get("session") or "L1"
    print(f"source connected: session={session}", flush=True)

    try:
        async for raw in ws:
            try:
                msg = json.loads(raw)
            except json.JSONDecodeError:
                continue

            msg_type = msg.get("type")
            if msg_type == "CAPTION_UPDATE":
                if "session" not in msg and session:
                    msg["session"] = session

                # Serialize after adding the session if necessary.
                outgoing = json.dumps(msg)

                # Accept/store once, then enqueue only accepted updates.
                if accept_caption(msg, raw_json=outgoing):
                    enqueue_live_update(
                        session=str(msg.get("session") or "L1"),
                        segment=int(msg["segment"]),
                        revision=int(msg["revision"]),
                        is_final=bool(msg.get("final", False)),
                        raw_message=outgoing,
                    )
            elif msg_type == "SOURCE_DONE":
                # Test-control message. The specification does not require it
                # to be forwarded to clients.
                print("source finished", flush=True)
            else:
                # Forward compatibility: ignore fields/messages this baseline
                # doesn't understand rather than crashing.
                continue
    finally:
        print("source disconnected", flush=True)

def parse_cursor_integer(value: Any) -> int:
    if isinstance(value, bool):
        raise ValueError("Cursor cannot be a boolean")

    if isinstance(value, int):
        parsed = value

    elif isinstance(value, float):
        if not math.isfinite(value) or not value.is_integer():
            raise ValueError("Cursor must be a finite whole number")
        parsed = int(value)

    elif isinstance(value, str):
        parsed = int(value)

    else:
        raise ValueError("Unsupported cursor type")

    if parsed < 0:
        raise ValueError("Cursor cannot be negative")

    return parsed

async def handle_client(ws, hello: dict[str, Any]) -> None:
    client_id = hello.get("client_id")

    session = hello.get("session") or "L1"

    # Convert and validate the finalized resume cursor.
    try:
        last_segment = parse_cursor_integer(
            hello.get("last_segment", 0)
        )
        last_revision = parse_cursor_integer(
            hello.get("last_revision", 0)
        )
    except (TypeError, ValueError, OverflowError):
        await ws.close(
            code=1008,
            reason="Resume cursor must contain nonnegative whole numbers",
        )
        return

    # Normalize cursor: segment 0 has no revisions; positive segments allow omitted/zero revision.
    if last_segment == 0:
        last_revision = 0

    # Convert the history window, defaulting invalid input to 30 seconds.
    requested_history = hello.get("history_seconds", 30)

    try:
        if isinstance(requested_history, bool):
            raise ValueError("History window cannot be a boolean")

        history_seconds = float(requested_history)
    except (TypeError, ValueError, OverflowError):
        history_seconds = 30.0

    if not math.isfinite(history_seconds):
        history_seconds = 30.0

    # Clamp the window to between 0 and 60 seconds.
    history_seconds = min(60.0, max(0.0, history_seconds))

    client = ClientConnection(
        ws=ws,
        session=session,
    )

    # Snapshot creation and registration must not suspend.
    now = time.time()
    prune_history(now)

    items = STATE.get_history(
        session_id=session,
        last_segment=last_segment,
        last_revision=last_revision,
        history_seconds=history_seconds,
        now=now,
    )

    # The first application message is always HISTORY,
    # including when its items list is empty.
    client.queue.put_nowait(json.dumps({
        "type": "HISTORY",
        "items": items,
    }))

    # Send active provisional state separately from HISTORY.
    session_state = STATE.sessions.get(session)

    if session_state is not None:
        active = session_state.segments.get(
            session_state.latest_active_segment
        )

        if active is not None and not active.final:
            client.queue.enqueue_caption(
                segment=active.segment,
                revision=active.revision,
                is_final=False,
                payload=active.raw_json or json.dumps(dict(active.raw_msg)),
            )

    # Register before allowing another coroutine to run.
    CLIENTS.add(client)

    # The sender now owns all application-message sends.
    sender_task = asyncio.create_task(client_sender(client))

    print(
        f"client connected: id={client_id}; clients={len(CLIENTS)}",
        flush=True,
    )

    try:
        async for _ in ws:
            pass

    except websockets.exceptions.ConnectionClosed:
        pass

    finally:
        client.closing = True
        CLIENTS.discard(client)

        sender_task.cancel()
        await asyncio.gather(
            sender_task,
            return_exceptions=True,
        )

        # Finish any overflow-triggered socket close.
        if client.close_task is not None:
            await asyncio.gather(
                client.close_task,
                return_exceptions=True,
            )

        # Release queued payloads for this disconnected client.
        while True:
            try:
                client.queue.get_nowait()
            except asyncio.QueueEmpty:
                break
            else:
                client.queue.task_done()

        print(
            f"client disconnected: id={client_id}; clients={len(CLIENTS)}",
            flush=True,
        )


async def handler(ws) -> None:
    try:
        raw = await asyncio.wait_for(ws.recv(), timeout=5)
        hello = json.loads(raw)
    except (asyncio.TimeoutError, json.JSONDecodeError):
        await ws.close(code=1008, reason="Expected a valid hello message")
        return

    msg_type = hello.get("type")
    if msg_type == "SOURCE_HELLO":
        await handle_source(ws, hello)
    elif msg_type == "CLIENT_HELLO":
        await handle_client(ws, hello)
    else:
        await ws.close(code=1008, reason="Expected SOURCE_HELLO or CLIENT_HELLO")


async def periodic_prune_task(interval: float = 5.0) -> None:
    """Periodically prune expired history when the source is idle."""
    while True:
        try:
            await asyncio.sleep(interval)
            prune_history()
        except asyncio.CancelledError:
            break
        except Exception:
            pass


async def main_async(port: int) -> None:
    prune_task = asyncio.create_task(periodic_prune_task())
    try:
        async with websockets.serve(
            handler,
            "0.0.0.0",
            port,
            max_size=2**20,
            ping_interval=20,
            ping_timeout=20,
        ):
            print(f"LiveRecall baseline listening on ws://0.0.0.0:{port}", flush=True)
            await asyncio.Future()
    finally:
        prune_task.cancel()
        try:
            await prune_task
        except asyncio.CancelledError:
            pass


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=8765)
    args = parser.parse_args()
    try:
        asyncio.run(main_async(args.port))
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
